export function getEventsByCategory(categoryId) {
  if (!categoryId || categoryId === "caos") {
    return [...EVENTS_DB];
  }
  return EVENTS_DB.filter((e) => e.category === categoryId);
}

export function getRandomEvent(categoryId, excludeIds = []) {
  const pool = getEventsByCategory(categoryId).filter((e) => !excludeIds.includes(e.id));
  if (pool.length === 0) return null;
  return pool[Math.floor(Math.random() * pool.length)];
}
